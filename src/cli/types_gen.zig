const testing = std.testing;

/// Intern a name and return the raw u16 the wire structs carry
/// (`StringId` is a typed index; `name_string_id` fields are u16).
fn internU16(strings: *StringTable, name: []const u8) !u16 {
    return @intFromEnum(try strings.intern(testing.allocator, name));
}
